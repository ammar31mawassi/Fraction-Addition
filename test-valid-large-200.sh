gcd_abs() {
    local a="$1"
    local b="$2"
    local t

    if (( a < 0 )); then
        a=$(( -a ))
    fi
    if (( b < 0 )); then
        b=$(( -b ))
    fi

    while (( b != 0 )); do
        t=$(( a % b ))
        a="$b"
        b="$t"
    done

    printf '%d' "$a"
}

expected_sum() {
    local n1="$1"
    local d1="$2"
    local n2="$3"
    local d2="$4"
    local rn=$(( n1 * d2 + n2 * d1 ))
    local rd=$(( d1 * d2 ))
    local g

    if (( rd == 0 )); then
        if (( rn == 0 )); then
            printf 'NaN ("not a number")'
        elif (( rn < 0 )); then
            printf -- '-\342\210\236'
        else
            printf '+\342\210\236'
        fi
        return
    fi

    if (( rn == 0 )); then
        printf '0'
        return
    fi

    g=$(gcd_abs "$rn" "$rd")
    rn=$(( rn / g ))
    rd=$(( rd / g ))

    if (( rd < 0 )); then
        rn=$(( -rn ))
        rd=$(( -rd ))
    fi

    if (( rd == 1 )); then
        printf '%d' "$rn"
    else
        printf '%d/%d' "$rn" "$rd"
    fi
}

run_case() {
    local arg1="$1"
    local arg2="$2"
    local n1="$3"
    local d1="$4"
    local n2="$5"
    local d2="$6"
    local expected
    local out_file
    local err_file
    local actual_out
    local actual_err
    local status

    total=$(( total + 1 ))
    expected=$(expected_sum "$n1" "$d1" "$n2" "$d2")
    out_file=$(mktemp)
    err_file=$(mktemp)

    ./add-frac "$arg1" "$arg2" >"$out_file" 2>"$err_file"
    status=$?
    actual_out=$(cat "$out_file")
    actual_err=$(cat "$err_file")
    rm -f "$out_file" "$err_file"

    if [ "$actual_out" != "$expected" ] || [ -n "$actual_err" ]; then
        failed=$(( failed + 1 ))
        printf 'FAIL case %03d: ./add-frac %q %q\n' "$total" "$arg1" "$arg2"
        printf '  exit=%s\n' "$status"
        printf '  stdout=%q\n' "$actual_out"
        printf '  stderr=%q\n' "$actual_err"
        printf '  expected_stdout=%q\n' "$expected"
    fi
}

